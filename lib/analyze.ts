const NAME = String.raw`((?:[A-Z][\w.&'’-]*|\d{4})(?:\s(?:[A-Z][\w.&'’-]*|of|for|and|the|\d{4})){0,6})`;
const LEAD = String.raw`(?:[Aa]ccording to|[Ss]tud(?:y|ies) (?:by|from|at|in)|[Rr]esearchers? (?:at|from)|[Ss]cientists? (?:at|from)|[Pp]ublished in|[Rr]eport (?:by|from)|[Ss]urvey (?:by|from)|[Oo]riginated (?:with|from)|[Cc]redited to|[Tt]he work of|[Cc]oined by|[Ss]tarted with|[Ff]irst (?:appeared|reported|claimed) (?:in|by)|[Ss]ays|[Ss]aid)`;
const BAD = /^(The|This|That|It|They|He|She|We|Some|Many|One|A|An|In|On|At|For)$/;
/** Named sources a passage points to ("according to the Institute of X"), to search for as the next hop. */
export function attributions(text: string): string[] {
  const out: string[] = [];
  for (const m of strip(text).matchAll(new RegExp(LEAD + String.raw`\s+(?:the\s+)?` + NAME, "g"))) {
    const name = m[1].replace(/\s+(of|for|and|the)$/, "").trim();
    if (name.length > 3 && !BAD.test(name) && !out.includes(name)) out.push(name);
  }
  return out.slice(0, 2);
}

export function links(paragraph: string): string[] {
  return [...paragraph.matchAll(/\]\((https?:\/\/[^)\s]+)\)/g)].map((m) => m[1].replace(/[.,]$/, ""));
}

const DISPUTE = /\b(myth|debunk\w*|misconception|fact[- ]?check\w*|fiction|false|untrue|not true|no evidence|misleading|hoax|urban legend|incorrect|busted|misattribut\w*|misquot\w*|apocryphal|never said|did not say|didn't say|no record)\b/i;
/** True when the page frames the claim as false: dispute words in its title or the matched passage's surroundings. */
export const isDisputed = (title: string, context: string) => DISPUTE.test(title || "") || DISPUTE.test(strip(context));

export type QuoteCheck = { status: "verified" | "close" | "not_found"; passage?: string };
/** Does a page really contain the wording someone attributes to it? exact (normalised) > close (>=80% of terms in one sentence) > not found. */
export function quoteMatch(wording: string, text: string): QuoteCheck {
  const nt = ` ${norm(text)} `, w = strip(wording);
  const has = (s: string) => nt.includes(` ${norm(s)} `);
  if (norm(w).length >= 15 && has(w)) return { status: "verified", passage: bestPassage(text, w)?.sentence };
  // quotes often carry extra text (a citation tail, a lead-in sentence): any substantial sentence of it found verbatim counts
  const sents = w.split(/(?<=[.!?])\s+/).map((s) => s.trim()).filter((s) => norm(s).split(" ").length >= 6);
  for (const s of sents) if (has(s)) return { status: "verified", passage: s };
  const longest = [...sents].sort((a, b) => b.length - a.length)[0];
  for (const q of [w, longest]) {
    const bp = q ? bestPassage(text, q) : null;
    if (bp && bp.score >= 0.8) return { status: "close", passage: bp.sentence };
  }
  return { status: "not_found" };
}

/**
 * For an UPSTREAM page (the study or report a claim credits), the wording is rarely the claim's own: "90 to 95 percent" vs "95%".
 * Accept a sentence that carries a nearby figure, or that shares enough of the claim's terms.
 */
export function loosePassage(text: string, claim: string): { sentence: string; ctx: string; score: number } | null {
  const ct = new Set(toks(claim)), cn = nums(strip(claim));
  if (!ct.size) return null;
  const paras = text.split(/\n+/);
  let best: { sentence: string; ctx: string; score: number } | null = null;
  paras.forEach((para, i) => {
    if (/^\s*#/.test(para)) return;
    for (const raw of para.split(SENT)) {
      const s = strip(raw);
      if (s.length < 25 || s.length > 600 || s.endsWith("?") || JUNK.test(s)) continue;
      const st = new Set(toks(s));
      let hit = 0;
      ct.forEach((t) => st.has(t) && hit++);
      const score = hit / ct.size;
      // upstream figures must be genuinely close ("90 to 95" for 95), much tighter than the 35% used to flag a changed number
      const figure = cn.length > 0 && nums(s).some((x) => cn.some((c) => Math.abs(x - c) / Math.max(c, 1e-9) <= 0.12));
      if (!((figure && score >= 0.2) || score >= 0.5)) continue;
      const rank = score + (figure ? 0.5 : 0);
      if (!best || rank > best.score) best = { sentence: s, score: rank, ctx: strip(paras.slice(Math.max(0, i - 1), i + 2).join(" ")).slice(0, 440) };
    }
  });
  return best;
}
